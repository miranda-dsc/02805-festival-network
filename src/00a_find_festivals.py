import json
import re
from datetime import datetime, timezone
from pathlib import Path

import pandas as pd

EVENTS = Path("data/raw/events.json")  
OUT = Path("data/processed")
OUT.mkdir(parents=True, exist_ok=True)

YEARS = list(range(2015, 2026))  
MIN_YEARS = 4    
MIN_ACTS = 30

EXCLUDE = {
    # outside Europe
    "bonnaroo", "camp flog gnaw", "coachella valley music and arts weekend 1",
    "coachella valley music and arts weekend 2", "das energi", "hulaween",
    "osheaga", "stagecoach", "lollapalooza", "pitchfork", "ultra music",
    # not a music festival
    "leeds international film",
    # near-identical second weekend of the same festival
    "tomorrowland weekend 2",
}

def festival_key(desc: str) -> str:
    """Turn 'Glastonbury Festival 2023' and 'Glastonbury 2019' into 'glastonbury'."""
    key = desc.lower()
    key = re.sub(r"\b(19|20)\d{2}\b", " ", key)               # years
    key = re.sub(r"\[.*?\]|\(.*?\)", " ", key)                 # [core], (notes)
    key = re.sub(r"\bfestival\b|\bfest\b", " ", key)
    key = re.sub(r"[^a-z0-9 ]", " ", key)
    return re.sub(r"\s+", " ", key).strip()


events = json.loads(EVENTS.read_text(encoding="utf-8"))

rows = []
for cf_id, info in events.items():
    if "startDate" not in info:          
        continue
    start = datetime.fromtimestamp(info["startDate"], timezone.utc)
    rows.append({
        "festival": festival_key(info["desc"]),
        "year": start.year,
        "id": cf_id,
        "desc": info["desc"],
        "n_acts": info.get("numActs", 0),
    })

df = pd.DataFrame(rows)
df = df[~df["festival"].isin(EXCLUDE)]
df = df[df["year"].isin(YEARS) & (df["n_acts"] >= MIN_ACTS)]

# If a festival has two clashfinders in the same year, keep the biggest
df = df.sort_values("n_acts", ascending=False).drop_duplicates(["festival", "year"])

# Keep festivals present in enough years
counts = df.groupby("festival")["year"].nunique()
keep = counts[counts >= MIN_YEARS].index
candidates = df[df["festival"].isin(keep)].sort_values(["festival", "year"])

candidates.to_csv(OUT / "candidate_festivals.csv", index=False)
print(f"{len(keep)} festivals with at least {MIN_YEARS} of {YEARS}")
print(f"{len(candidates)} clashfinders to download\n")
print(candidates.groupby("festival")["year"].apply(lambda y: ", ".join(map(str, y))).to_string())

# Write the list of IDs for the download script, grouped by festival
lines = ["# Generated by src/00a_find_festivals.py", ""]
for festival, group in candidates.groupby("festival"):
    lines.append(f"# {festival}")
    lines.extend(group["id"].tolist())
    lines.append("")
Path("data/clashfinder_ids.txt").write_text("\n".join(lines), encoding="utf-8")
print("\nSaved the IDs in data/clashfinder_ids.txt")